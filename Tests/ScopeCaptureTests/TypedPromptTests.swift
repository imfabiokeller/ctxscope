import Foundation
import ScopeCore
import Testing

@testable import ScopeCapture

@Suite("typed prompts")
struct TypedPromptTests {
  private static func user(
    _ content: Any, promptID: String? = nil, extra: [String: Any] = [:]
  ) throws -> TranscriptEntry {
    var object: [String: Any] = [
      "type": "user", "uuid": UUID().uuidString,
      "message": ["role": "user", "content": content],
    ]
    if let promptID { object["promptId"] = promptID }
    for (key, value) in extra { object[key] = value }
    let data = try JSONSerialization.data(withJSONObject: object)
    return TranscriptEntry(try JSONValue(parsing: data))
  }

  private static func typed(_ entries: [TranscriptEntry]) -> [Bool] {
    var reader = EntryReader()
    return entries.map { entry in
      reader.learn(from: entry)
      return reader.pieces(of: entry).contains { $0.isPrompt }
    }
  }

  @Test("a typed prompt starts a task; the interruption under the same prompt id does not")
  func samePrompt() throws {
    let result = Self.typed([
      try Self.user("Refactor the retry policy", promptID: "p1"),
      try Self.user([["type": "text", "text": "[Request interrupted by user]"]], promptID: "p1"),
      try Self.user("And now the tests", promptID: "p2"),
    ])
    #expect(result == [true, false, true])
  }

  @Test("tool results, harness notes, summaries and task reports are not prompts")
  func notPrompts() throws {
    let result = Self.typed([
      try Self.user([["type": "tool_result", "tool_use_id": "t", "content": "ok"]]),
      try Self.user("Caveat: generated by a command", promptID: "p1", extra: ["isMeta": true]),
      try Self.user(
        "Summary of the conversation", promptID: "p2", extra: ["isCompactSummary": true]),
      try Self.user(
        "<task-notification>\nthe agent finished", promptID: "p3",
        extra: ["origin": ["kind": "task-notification"]]),
      try Self.user("<task-notification>\nthe agent finished"),
      try Self.user("[Request interrupted by user for tool use]"),
      try Self.user("   "),
    ])
    #expect(result == [false, false, false, false, false, false, false])
  }

  @Test("a transcript that writes no prompt id counts every typed turn")
  func noPromptID() throws {
    let result = Self.typed([try Self.user("first"), try Self.user("second")])
    #expect(result == [true, true])
  }

  @Test("only the first text block of a prompt is its block")
  func oneBlock() throws {
    var reader = EntryReader()
    let entry = try Self.user(
      [["type": "text", "text": "look at this"], ["type": "text", "text": "and this"]],
      promptID: "p1")
    reader.learn(from: entry)
    #expect(reader.pieces(of: entry).map(\.isPrompt) == [true, false])
    #expect(reader.pieces(of: entry).map(\.isPrompt) == [true, false])
  }

  /// Every user turn of compaction-session comes from a background task.
  @Test(
    "each fixture lane lists its prompts in the order they entered",
    arguments: [
      ("short-session", 6), ("compaction-session", 0), ("subagent-lane", 1), ("parallel-calls", 0),
    ])
  func fixtures(name: String, count: Int) throws {
    let lane = try AdapterTests.lane(name).lane
    #expect(lane.prompts.count == count)
    let prompts = lane.prompts.map { lane.segments[$0.rawValue] }
    #expect(prompts.allSatisfy { $0.band == .user && $0.label == "User prompt" })
    #expect(prompts.map(\.born) == prompts.map(\.born).sorted())
  }
}
